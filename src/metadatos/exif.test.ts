import { describe, expect, it } from 'vitest';
import { analizarMetadatos } from './exif';

describe('detección pura de metadatos', () => {
  it('reconoce un JPEG con EXIF y detecta GPS + cámara desde el IFD0', () => {
    // JPEG mínimo: SOI + APP1(EXIF, little-endian) con IFD0 = { Model(0x0110), GPSInfo(0x8825) } + EOI.
    const jpeg = new Uint8Array([
      0xff, 0xd8, // SOI
      0xff, 0xe1, 0x00, 0x2e, // APP1, longitud 46
      0x45, 0x78, 0x69, 0x66, 0x00, 0x00, // "Exif\0\0"
      0x49, 0x49, 0x2a, 0x00, 0x08, 0x00, 0x00, 0x00, // TIFF little-endian, IFD0 en +8
      0x02, 0x00, // IFD0: 2 entradas
      0x10, 0x01, 0x02, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // Model
      0x25, 0x88, 0x04, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // GPSInfo
      0x00, 0x00, 0x00, 0x00, // siguiente IFD = 0
      0xff, 0xd9, // EOI
    ]);
    const r = analizarMetadatos(jpeg);
    expect(r.formato).toBe('jpeg');
    expect(r.categorias).toEqual(['ubicacion', 'camara']);
  });

  it('un JPEG sin segmento EXIF no reporta categorías', () => {
    const jpeg = new Uint8Array([0xff, 0xd8, 0xff, 0xd9]); // SOI + EOI, nada más
    const r = analizarMetadatos(jpeg);
    expect(r.formato).toBe('jpeg');
    expect(r.categorias).toEqual([]);
  });

  it('reconoce un PNG y detecta texto (tEXt) y fecha (tIME)', () => {
    const png = new Uint8Array([
      0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, // firma PNG
      0x00, 0x00, 0x00, 0x05, 0x74, 0x45, 0x58, 0x74, 0x41, 0x42, 0x00, 0x43, 0x44, 0x00, 0x00, 0x00, 0x00, // tEXt
      0x00, 0x00, 0x00, 0x07, 0x74, 0x49, 0x4d, 0x45, 0x07, 0xe0, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // tIME
      0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0x00, 0x00, 0x00, 0x00, // IEND
    ]);
    const r = analizarMetadatos(png);
    expect(r.formato).toBe('png');
    expect(r.categorias).toEqual(['fecha', 'otros']);
  });

  it('un fichero que no es imagen conocida devuelve formato null', () => {
    const otro = new Uint8Array([0x25, 0x50, 0x44, 0x46]); // "%PDF"
    const r = analizarMetadatos(otro);
    expect(r.formato).toBeNull();
    expect(r.categorias).toEqual([]);
  });
});
